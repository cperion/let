-- Emit decoding contracts from the revision-6 manifest. No legacy opcode aliases.
local directory=arg[0]:match('^(.*)/[^/]*$') or '.'
package.path=directory..'/?.lua;'..directory..'/../gen/?.lua;'..package.path
local manifest=require('opcodes')
local semantics=require('semantics')
local transfer_names,transfer_indices={},{}
for _,name in ipairs(manifest.operations) do
    local transfer=assert(semantics.transfers[name],'missing semantic transfer '..name).kind
    if transfer_indices[transfer]==nil then
        transfer_indices[transfer]=#transfer_names
        transfer_names[#transfer_names+1]=transfer:upper()
    end
end
local output=assert(arg[1],'output header required')
local lines={
    '/* Generated by tools/gen_opcodes.lua from tools/opcodes.lua. */',
    '#pragma once', '#include <stddef.h>', '#include <stdint.h>',
    ('enum { ABC_ISA_REVISION = %d };'):format(manifest.revision),
}
local function emit(line) lines[#lines+1]=line end
local function enumeration(type_name,prefix,names,count_name)
    emit('enum '..type_name..' {')
    for index,name in ipairs(names) do emit(('    %s%s = %d,'):format(prefix,name,index-1)) end
    emit(('    %s = %d'):format(count_name,#names))
    emit('};')
end
local opcode_names={}
for _,instruction in ipairs(manifest.ops) do opcode_names[#opcode_names+1]=instruction.name end
enumeration('abc_opcode','OP_',opcode_names,'OP_COUNT')
local extended_names={}
for _,instruction in ipairs(manifest.ext_ops) do extended_names[#extended_names+1]=instruction.name end
enumeration('abc_extended_selector','EXT_',extended_names,'EXT_COUNT')
enumeration('abc_operation','ABC_OPERATION_',manifest.operations,'ABC_OPERATION_COUNT')
enumeration('abc_instruction_kind','K_',manifest.kind_order,'ABC_INSTRUCTION_KIND_COUNT')
enumeration('abc_transfer_kind','ABC_TRANSFER_',transfer_names,'ABC_TRANSFER_KIND_COUNT')
enumeration('abc_operand_layout','ABC_LAYOUT_',manifest.layout_order,'ABC_OPERAND_LAYOUT_COUNT')
enumeration('abc_stack_role','ABC_STACK_ROLE_',manifest.stack_role_order,'ABC_STACK_ROLE_COUNT')
enumeration('abc_memory_action','M_',manifest.memory_action_order,'ABC_MEMORY_ACTION_COUNT')
emit('enum abc_operand_stack { ABC_STACK_A, ABC_STACK_B, ABC_STACK_NONE };')
emit([=[
typedef struct {
    uint16_t operation;
    uint8_t transfer_kind;
    uint8_t kind;
    uint8_t operand_layout;
    uint8_t minimum_profile;
    uint8_t stack_role;
    uint8_t selected_stack;
    uint8_t encoded_length;
    uint8_t memory_action;
    uint8_t memory_width;
    uint8_t sign_extend;
    /* Optional selected unary kind transition: abc_cell_kind + 1, zero absent. */
    uint8_t unary_input_kind, unary_result_kind;
    const char *name;
} abc_instruction_metadata;

/* A borrowed view of one decoded instruction, not a residual representation. */
typedef struct {
    const abc_instruction_metadata *metadata;
    const uint8_t *operands;
    uint32_t length;
    uint8_t selected_stack;
} abc_decoded_instruction;
]=])
local function metadata_initializer(instruction)
    local memory=instruction.mem or {action=0,width=0,sign=0}
    local operation=manifest.operations[instruction.operation+1]
    local transfer=semantics.transfers[operation]
    return ('{%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,"%s"}'):format(
        instruction.operation,transfer_indices[semantics.transfers[operation].kind],instruction.kind,instruction.layout,instruction.profile,
        instruction.role,instruction.stack,instruction.len,memory.action,memory.width,
        memory.sign,transfer.input_kind or 0,transfer.result_kind or 0,instruction.name)
end
emit('static const abc_instruction_metadata abc_core_instructions[256] = {')
for _,instruction in ipairs(manifest.ops) do
    emit(('    [OP_%s] = %s,'):format(instruction.name,metadata_initializer(instruction)))
end
emit('};')
emit('static const abc_instruction_metadata abc_extended_instructions[256] = {')
for _,instruction in ipairs(manifest.ext_ops) do
    emit(('    [EXT_%s] = %s,'):format(instruction.name,metadata_initializer(instruction)))
end
emit('};')
emit([=[
/* Used at format boundaries. Successful decoding establishes the full length,
   including a switch table or an EXT selector. Profiles and effects are verified
   by the consumer. Execution bindings need not repeat these format checks. */
static inline int abc_decode_instruction(const uint8_t *code, size_t remaining,
                                         abc_decoded_instruction *decoded) {
    if (!remaining) return 0;
    const abc_instruction_metadata *metadata = &abc_core_instructions[code[0]];
    unsigned operand_offset = 1;
    uint8_t selected_stack = metadata->selected_stack;
    if (metadata->kind == K_EXT) {
        if (remaining < 2) return 0;
        metadata = &abc_extended_instructions[code[1]];
        operand_offset = 2;
    }
    uint32_t length = metadata->encoded_length;
    if (!length || remaining < length) return 0;
    if (metadata->kind == K_SWITCH) {
        uint32_t count = (uint32_t)code[1] | ((uint32_t)code[2] << 8);
        length += 4 * count;
        if (remaining < length) return 0;
    }
    decoded->metadata = metadata;
    decoded->operands = code + operand_offset;
    decoded->length = length;
    decoded->selected_stack = selected_stack;
    return 1;
}
]=])
local file=assert(io.open(output,'wb'))
assert(file:write(table.concat(lines,'\n'),'\n'))
assert(file:close())
