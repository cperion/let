local states = {}
for _, p in ipairs(AB) do for k = 0, CDEPTH do states[#states + 1] = { a = p.a, b = p.b, k = k } end end
local ARGS = "V *asp, V *bsp, V *csp, V h0, V h1, V h2, V h3, V c0, V c1, V c2, V c3"
local PASS = "asp, bsp, csp, h0, h1, h2, h3, c0, c1, c2, c3"
if not JIT then
  -- the interpreter needs ip and one free register for the dispatch jump
  ARGS = "const uint8_t *ip, V *asp, V *bsp, V *csp, V h0, V h1, V h2, V h3, V c0, V c1, V c2"
  PASS = "ip, asp, bsp, csp, h0, h1, h2, h3, c0, c1, c2"
end
local PREAMBLE = ([[
#include <stdint.h>
#include <string.h>
#include "opcodes.h"
typedef uint64_t V;
#define PN __attribute__((preserve_none))
#define ARGS %s
#define PASS %s
typedef PN V (*H)(ARGS);
static inline V vm_pow(V x, V e) { V r = 1; while (e) { if (e & 1) r *= x; x *= x; e >>= 1; } return r; }
 ]]):format(ARGS, PASS)
local out = {}
local function emit(x) out[#out + 1] = x end

if JIT then
  -------------------------------------------------------- JIT stencils
  local JOPS = {}
  for _, p in ipairs(OPS) do JOPS[#JOPS + 1] = p end
  local PSEUDO = {}
  for _, kind in ipairs({ "CGETD", "CSETD" }) do for _, X in ipairs({ "A", "B" }) do for d = 1, 3 do
    local name = ("%s_%s_%d"):format(kind, X, d)
    JOPS[#JOPS + 1] = { name, 1, "n" }
    PSEUDO[#PSEUDO + 1] = { kind = kind, X = X, d = d, id = #JOPS - 1 }
  end end end
  local OPCD = {}
  for i, p in ipairs(OPS) do
    if p[3] == "opc" then
      OPCD[i - 1] = {}
      local n, X = p[1]:match("^(%u+)C_(%u)$")
      for d = 0, 3 do JOPS[#JOPS + 1] = { ("OPCD_%s_%s_%d"):format(n, X, d), 1, "n" }; OPCD[i - 1][d + 1] = #JOPS - 1 end
    end
  end
  local function empty_only(name) return name:match("^CALL_") or name:match("^TCALL") or name:match("^RET") end
  emit("/* generated by gen.lua, mode " .. MODE .. " */")
  emit(PREAMBLE)
  emit("extern PN V HOLE_NEXT(ARGS);\nextern PN V HOLE_TAKEN(ARGS);\nextern char HOLE_IMM[], HOLE_IMM2[], HOLE_FINAL[];")
  local names, FALL, TAKEN, EFF = {}, {}, {}, {}
  for _, s in ipairs(states) do
    for _, p in ipairs(JOPS) do
      local b = builder(s)
      local kind
      if empty_only(p[1]) and (s.a + s.b + s.k > 0) then b:line("return 0;"); kind = "end"
      else kind = SEM[p[1]](b) end
      if kind ~= "done" and kind ~= "end" then b:line(b:next()) end
      local name = ("s_%s_%s"):format(key(s), p[1])
      names[#names + 1] = name
      emit(("PN V %s(ARGS) {"):format(name))
      for _, l in ipairs(b.L) do emit("  " .. l) end
      emit("}")
      FALL[#FALL + 1] = b.fall and sid(b.fall) or 255
      TAKEN[#TAKEN + 1] = b.tk and sid(b.tk) or 255
      if s.a == 0 and s.b == 0 and s.k == 0 then EFF[#EFF + 1] = { b.dfall or { 0, 0, 0 }, b.dtk or { 0, 0, 0 } } end
    end
  end
  -- conform stencils: operand bank (a,b) -> (a2,b2), and C k -> k2
  local function conform_stack(b, X, to)
    local s = b.s
    local c = cnt(s, X)
    local vals = {}
    for i = 0, c - 1 do vals[#vals + 1] = b:tmp(b:at(X, i)) end
    while #vals > to do b:line(("*%s++ = %s;"):format(SP[X], table.remove(vals))) end
    while #vals < to do vals[#vals + 1] = b:tmp("*--" .. SP[X]) end
    return vals
  end
  for _, f in ipairs(AB) do for _, t in ipairs(AB) do
    local b = builder({ a = f.a, b = f.b, k = 0 })
    local va = conform_stack(b, "A", t.a)
    local vb = conform_stack(b, "B", t.b)
    b.s.a, b.s.b = t.a, t.b
    for i = 0, t.a - 1 do b:raw(b:at("A", i), va[i + 1]) end
    for i = 0, t.b - 1 do b:raw(b:at("B", i), vb[i + 1]) end
    local name = ("k_ab_%d%d_%d%d"):format(f.a, f.b, t.a, t.b)
    names[#names + 1] = name
    emit(("PN V %s(ARGS) {"):format(name))
    for _, l in ipairs(b.L) do emit("  " .. l) end
    emit("  [[clang::musttail]] return HOLE_NEXT(PASS);\n}")
  end end
  for kf = 0, CDEPTH do for kt = 0, CDEPTH do
    local b = builder({ a = 0, b = 0, k = kf })
    local vc = conform_stack(b, "C", kt)
    b.s.k = kt
    for i = 0, kt - 1 do b:raw(b:at("C", i), vc[i + 1]) end
    local name = ("k_c_%d_%d"):format(kf, kt)
    names[#names + 1] = name
    emit(("PN V %s(ARGS) {"):format(name))
    for _, l in ipairs(b.L) do emit("  " .. l) end
    emit("  [[clang::musttail]] return HOLE_NEXT(PASS);\n}")
  end end
  local f = assert(io.open(OUT, "w")); f:write(table.concat(out, "\n"), "\n"); f:close()

  local base = OUT:gsub("%.c$", "")
  local of = assert(io.open(base .. "_order.txt", "w")); of:write(table.concat(names, "\n"), "\n"); of:close()
