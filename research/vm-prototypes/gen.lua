local nh = 0
-- handlers that rarely run are marked cold, so the compiler moves them out of the hot code
local function is_cold(name)
  return name == "HALT" or name == "ABORT" or name:match("^CHK") or name:match("^DIV") or name:match("^REM")
      or name:match("^POW") or name == "CALL_A" or name == "CALL_B" or name == "TCALL" or name == "RET"
end
-- emitted grouped by opcode, so one instruction's handlers for all cache states sit together
for _, s in ipairs(states) do
  for _, p in ipairs(OPS) do
    local b = builder(s)
    local kind = SEM[p[1]](b)
    emit(("static PN %sV h_%s_%s(ARGS) {"):format(is_cold(p[1]) and "__attribute__((cold)) " or "", key(s), p[1]))
    for _, l in ipairs(b.L) do emit("  " .. l) end
    if kind ~= "done" and kind ~= "end" then emit(("  ip += %d;"):format(p[2])) end
    if kind ~= "end" then emit("  " .. b:next()) end
    emit("}")
    nh = nh + 1
  end
end
