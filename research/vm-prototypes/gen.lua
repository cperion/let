  M[#M + 1] = ("#define NSTATE %d\n#define NAB %d\n#define NCK %d\n#define NOPS %d\n#define NBANK %d")
    :format(#states, #AB, NCK, #JOPS, NBANK)
  M[#M + 1] = "#define PN __attribute__((preserve_none))"
  M[#M + 1] = "typedef PN uint64_t (*H)(uint64_t *, uint64_t *, uint64_t *" .. string.rep(", uint64_t", 8) .. ");"
  M[#M + 1] = "#define JIT_ENTER(f, a, b, c) ((H)(f))(a, b, c" .. string.rep(", 0", 8) .. ")"
  local aa, bb = {}, {}
  for _, p in ipairs(AB) do aa[#aa + 1] = p.a; bb[#bb + 1] = p.b end
  M[#M + 1] = "static const unsigned char ab_a[] = {" .. table.concat(aa, ",") .. "};"
  M[#M + 1] = "static const unsigned char ab_b[] = {" .. table.concat(bb, ",") .. "};"
  local ix = {}
  for a = 0, 4 do local row = {} for b = 0, 4 do row[#row + 1] = ABIX[a .. "," .. b] or 255 end ix[#ix + 1] = "{" .. table.concat(row, ",") .. "}" end
  M[#M + 1] = "static const unsigned char ab_index[5][5] = {" .. table.concat(ix, ",") .. "};"
  local function rows(T)
    local r = {}
    for i = 0, #states - 1 do
      local row = {}
      for j = 1, #JOPS do row[#row + 1] = T[i * #JOPS + j] end
      r[#r + 1] = "  {" .. table.concat(row, ",") .. "}"
    end
    return table.concat(r, ",\n")
  end
  M[#M + 1] = ("static const unsigned char st_fall[%d][NOPS] = {\n%s\n};"):format(#states, rows(FALL))
  M[#M + 1] = ("static const unsigned char st_taken[%d][NOPS] = {\n%s\n};"):format(#states, rows(TAKEN))
  local ef, et = {}, {}
  for _, e in ipairs(EFF) do
    ef[#ef + 1] = ("{%d,%d,%d}"):format(e[1][1], e[1][2], e[1][3])
    et[#et + 1] = ("{%d,%d,%d}"):format(e[2][1], e[2][2], e[2][3])
  end
  M[#M + 1] = "static const signed char eff_fall[NOPS][3] = {" .. table.concat(ef, ",") .. "};"
  M[#M + 1] = "static const signed char eff_taken[NOPS][3] = {" .. table.concat(et, ",") .. "};"
  local function pmap(kind)
    local r = {}
    for _, X in ipairs({ "A", "B" }) do
      local row = { 0, 0, 0, 0 }
      for _, p in ipairs(PSEUDO) do if p.kind == kind and p.X == X then row[p.d + 1] = p.id end end
      r[#r + 1] = "{" .. table.concat(row, ",") .. "}"
    end
    return table.concat(r, ",")
  end
  M[#M + 1] = "static const unsigned short cgetd_op[2][4] = {" .. pmap("CGETD") .. "};"
  local oc = {}
  for i = 0, #OPS - 1 do local v = OPCD[i] or { 0, 0, 0, 0 }; oc[#oc + 1] = "{" .. table.concat(v, ",") .. "}" end
  M[#M + 1] = "static const unsigned short opcd_op[][4] = {" .. table.concat(oc, ",") .. "};"
  M[#M + 1] = "static const unsigned short csetd_op[2][4] = {" .. pmap("CSETD") .. "};"
  local mf = assert(io.open(base .. "_meta.h", "w")); mf:write(table.concat(M, "\n"), "\n"); mf:close()
  io.stderr:write(("%s: %d states, %d stencils\n"):format(OUT, #states, #names))
  return
end

